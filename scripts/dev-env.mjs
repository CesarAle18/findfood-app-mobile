#!/usr/bin/env node
// Switches the app between environment profiles and starts Expo.
//
//   node scripts/dev-env.mjs local [donante|voluntario] [--no-start] [expo args...]
//     Mints a development JWT for a seeded findfood-api user and writes
//     .env.development.local (local profile, development builds only).
//   node scripts/dev-env.mjs real [--no-start] [expo args...]
//     Removes the generated .env.development.local so .env.local applies again.
//
// Options (environment): FINDFOOD_API_DIR (default ../findfood-api), DEV_API_HOST
// (default: first LAN IPv4), DEV_API_PORT (default 3000), DEV_TOKEN_TTL_HOURS (default 24).
// No dependencies: Node built-ins only.

import { Buffer } from "node:buffer";
import { spawn } from "node:child_process";
import { createHmac } from "node:crypto";
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { networkInterfaces } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const APP_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ENV_FILE = join(APP_ROOT, ".env.development.local");
const MARKER = "# generated by scripts/dev-env.mjs — do not commit";
const ROLES = ["donante", "voluntario"];
const USAGE = `Usage:
  npm run start:local -- [donante|voluntario] [--no-start] [expo args...]
  npm run start:real -- [--no-start] [expo args...]`;

function fail(message) {
  console.error(`dev-env: ${message}`);
  process.exit(1);
}

function positiveNumber(name, raw, fallback) {
  if (raw === undefined || raw.trim() === "") return fallback;
  const value = Number(raw);
  if (!Number.isFinite(value) || value <= 0) {
    fail(`${name} must be a positive number (got "${raw}").`);
  }
  return value;
}

function readPostmanEnv(apiDir) {
  const file = join(apiDir, "postman", "FindFood-local.postman_environment.json");
  if (!existsSync(file)) {
    fail(
      `${file} not found.\n` +
        "Run `npm run datos:prueba` in findfood-api first, or set FINDFOOD_API_DIR " +
        "to the findfood-api folder.",
    );
  }
  let parsed;
  try {
    parsed = JSON.parse(readFileSync(file, "utf8"));
  } catch (error) {
    fail(`${file} is not valid JSON (${error.message}). Re-run \`npm run datos:prueba\`.`);
  }
  const values = new Map();
  for (const entry of parsed?.values ?? []) {
    if (entry?.enabled !== false && typeof entry?.value === "string") {
      values.set(entry.key, entry.value);
    }
  }
  return { file, values };
}

function signHs256(payload, secret) {
  const encode = (value) => Buffer.from(JSON.stringify(value)).toString("base64url");
  const unsigned = `${encode({ alg: "HS256", typ: "JWT" })}.${encode(payload)}`;
  const signature = createHmac("sha256", secret).update(unsigned).digest("base64url");
  return `${unsigned}.${signature}`;
}

function lanIPv4() {
  for (const addresses of Object.values(networkInterfaces())) {
    for (const address of addresses ?? []) {
      const isIPv4 = address.family === "IPv4" || address.family === 4;
      // Skip loopback and link-local (169.254.x.x) addresses: phones cannot reach them.
      if (isIPv4 && !address.internal && !address.address.startsWith("169.254.")) {
        return address.address;
      }
    }
  }
  return undefined;
}

function isGeneratedEnvFile() {
  const firstLine = readFileSync(ENV_FILE, "utf8").replace(/^﻿/, "").split(/\r?\n/, 1)[0];
  return firstLine.trim() === MARKER;
}

function prepareLocal(args) {
  let role = "donante";
  if (args[0] !== undefined && !args[0].startsWith("-")) {
    if (!ROLES.includes(args[0])) {
      fail(`Unknown role "${args[0]}". Expected one of: ${ROLES.join(", ")}.\n${USAGE}`);
    }
    role = args.shift();
  }

  if (existsSync(ENV_FILE) && !isGeneratedEnvFile()) {
    fail(
      `${relative(APP_ROOT, ENV_FILE)} exists and was not generated by this script. ` +
        "Move or delete it before switching to the local profile.",
    );
  }

  const apiDir = resolve(APP_ROOT, process.env.FINDFOOD_API_DIR ?? "../findfood-api");
  const { file, values } = readPostmanEnv(apiDir);
  const secret = values.get("clave_jwt_local");
  const issuer = values.get("emisor_jwt_local");
  const userId = values.get(`id_${role}`);
  const missing = [
    ["clave_jwt_local", secret],
    ["emisor_jwt_local", issuer],
    [`id_${role}`, userId],
  ]
    .filter(([, value]) => !value)
    .map(([key]) => key);
  if (missing.length > 0) {
    fail(`${file} lacks ${missing.join(", ")}. Re-run \`npm run datos:prueba\` in findfood-api.`);
  }

  const ttlHours = positiveNumber("DEV_TOKEN_TTL_HOURS", process.env.DEV_TOKEN_TTL_HOURS, 24);
  const port = positiveNumber("DEV_API_PORT", process.env.DEV_API_PORT, 3000);
  if (!Number.isInteger(port) || port > 65535) {
    fail(`DEV_API_PORT must be a port number (got "${process.env.DEV_API_PORT}").`);
  }
  const host = process.env.DEV_API_HOST?.trim() || lanIPv4();
  if (!host) fail("No LAN IPv4 address found. Set DEV_API_HOST to this machine's IP.");

  const iat = Math.floor(Date.now() / 1000);
  const exp = iat + Math.round(ttlHours * 3600);
  const token = signHs256(
    { sub: userId, role: "authenticated", aud: "authenticated", iss: issuer, iat, exp },
    secret,
  );
  const apiUrl = `http://${host}:${port}`;

  writeFileSync(
    ENV_FILE,
    [
      MARKER,
      "# Local API profile (development only). Regenerate: npm run start:local",
      "EXPO_PUBLIC_APP_ENV=local",
      `EXPO_PUBLIC_API_URL=${apiUrl}`,
      `EXPO_PUBLIC_DEV_TOKEN=${token}`,
      "",
    ].join("\n"),
    { mode: 0o600 },
  );

  console.log(`Local API profile written to ${relative(APP_ROOT, ENV_FILE)}
  role:     ${role}
  user id:  ${userId}
  API URL:  ${apiUrl}${process.env.DEV_API_HOST ? "" : " (override with DEV_API_HOST)"}
  expires:  ${new Date(exp * 1000).toISOString()} (${ttlHours} h)`);
  return args;
}

function prepareReal(args) {
  const name = relative(APP_ROOT, ENV_FILE);
  if (!existsSync(ENV_FILE)) {
    console.log(`Real profile: no ${name} to remove; .env.local applies.`);
  } else if (isGeneratedEnvFile()) {
    rmSync(ENV_FILE);
    console.log(`Real profile: removed ${name}; .env.local applies.`);
  } else {
    console.warn(
      `dev-env: ${name} was not generated by this script, so it was kept. ` +
        "Its values override .env.local in development.",
    );
  }
  return args;
}

function startExpo(args) {
  // Run the Expo CLI with this Node binary: no shell, so arguments are passed
  // verbatim on every platform (npx.cmd would need shell: true on Windows).
  const cli = createRequire(import.meta.url).resolve("expo/bin/cli");
  const child = spawn(process.execPath, [cli, "start", "--clear", ...args], {
    cwd: APP_ROOT,
    stdio: "inherit",
  });
  child.on("error", (error) => fail(`Could not start Expo: ${error.message}`));
  child.on("exit", (code, signal) => process.exit(code ?? (signal ? 1 : 0)));
}

const [profile, ...rest] = process.argv.slice(2);
const noStart = rest.includes("--no-start");
const passthrough = rest.filter((arg) => arg !== "--no-start");

let expoArgs;
if (profile === "local") expoArgs = prepareLocal(passthrough);
else if (profile === "real") expoArgs = prepareReal(passthrough);
else fail(`Unknown profile "${profile ?? ""}".\n${USAGE}`);

if (!noStart) startExpo(expoArgs);
